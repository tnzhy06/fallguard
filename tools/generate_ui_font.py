"""Generate every UI glyph from Noto Sans SC (Pillow required).

python tools/generate_ui_font.py --font build/NotoSansSC.ttf
The generated header is committed; normal firmware builds need no font tools.
Font source: https://github.com/google/fonts/tree/main/ofl/notosanssc (OFL-1.1).
"""
import argparse
import hashlib
import math
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]


def raster(font_path, char, size, width=None, height=None):
    width = size if width is None else width
    height = size if height is None else height
    font = ImageFont.truetype(str(font_path), size * 4)
    if hasattr(font, "set_variation_by_axes"):
        font.set_variation_by_axes([500])
    image = Image.new("L", (width * 4, height * 4))
    draw = ImageDraw.Draw(image)
    # Use one common baseline, preserving consistent layout across glyphs.
    x = max(0, (width * 4 - font.getlength(char)) / 2) if height == 52 else 0
    draw.text((x, size * 4 * 0.86), char, font=font, fill=255, anchor="ls")
    image = image.resize((width, height), Image.Resampling.LANCZOS)
    levels = [(p * 3 + 127) // 255 for p in image.tobytes()]
    levels += [0] * (-len(levels) % 4)
    return [sum(levels[i + j] << (6 - j * 2) for j in range(4))
            for i in range(0, len(levels), 4)]


def advance(font_path, char, size):
    font = ImageFont.truetype(str(font_path), size * 4)
    if hasattr(font, "set_variation_by_axes"):
        font.set_variation_by_axes([500])
    return min(size, max(1, math.ceil(font.getlength(char) / 4)))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=ROOT / "ThirdParty/NotoSansSC/noto_sans_sc.h")
    args = parser.parse_args()
    source = (ROOT / "App/app_ui.c").read_text(encoding="utf-8")
    chars = sorted(set(c for c in source if "\u4e00" <= c <= "\u9fff"))
    digest = hashlib.sha256(args.font.read_bytes()).hexdigest()
    lines = ["/* Generated by tools/generate_ui_font.py. Noto Sans SC, OFL-1.1.",
             f" * Original TTF SHA-256: {digest}",
             " * See ThirdParty/NotoSansSC/OFL.txt. Packed 2bpp, MSB first. */",
             "#ifndef NOTO_SANS_SC_H", "#define NOTO_SANS_SC_H", "#include <stdint.h>",
             "typedef struct { uint32_t code; uint8_t px16[64], px20[100]; } app_ui_glyph_t;",
             "static const app_ui_glyph_t ui_glyphs[] = {"]
    for char in chars:
        arrays = [", ".join(f"0x{b:02X}" for b in raster(args.font, char, size)) for size in (16, 20)]
        lines.append(f"    {{0x{ord(char):04X}U, {{{arrays[0]}}}, {{{arrays[1]}}}}}, /* {char} */")
    lines += ["};", "typedef struct { uint32_t code; uint8_t pixels[400]; } app_ui_large_glyph_t;",
              "static const app_ui_large_glyph_t ui_large_glyphs[] = {"]
    for char in sorted(set("跌倒报警测试")):
        pixels = ", ".join(f"0x{b:02X}" for b in raster(args.font, char, 40))
        lines.append(f"    {{0x{ord(char):04X}U, {{{pixels}}}}}, /* {char} */")
    lines += ["};", "typedef struct { uint8_t advance16, advance20; uint8_t px16[64], px20[100]; } app_ui_ascii_glyph_t;",
              "static const app_ui_ascii_glyph_t ui_ascii_glyphs[] = {"]
    for code in range(32, 127):
        char = chr(code)
        arrays = [", ".join(f"0x{b:02X}" for b in raster(args.font, char, size)) for size in (16, 20)]
        widths = [advance(args.font, char, size) for size in (16, 20)]
        lines.append(f"    {{{widths[0]}U, {widths[1]}U, {{{arrays[0]}}}, {{{arrays[1]}}}}}, /* U+{code:04X} */")
    lines += ["};", '#define UI_CLOCK_CHARS "0123456789:-"',
              "#define UI_CLOCK_WIDTH 32U", "#define UI_CLOCK_HEIGHT 52U",
              "static const uint8_t ui_clock_glyphs[][416] = {"]
    for char in "0123456789:-":
        pixels = ", ".join(f"0x{b:02X}" for b in raster(args.font, char, 52, 32, 52))
        lines.append(f"    {{{pixels}}}, /* U+{ord(char):04X} */")
    lines += ["};", "#endif", ""]
    args.output.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {len(chars)} Chinese glyphs, 95 ASCII glyphs and 12 clock glyphs: {args.output}")


if __name__ == "__main__":
    main()
